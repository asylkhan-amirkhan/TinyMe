export function shopCollectionTitle(product: WorkshopProduct) {
  return product.collectionTitle ?? (product.collection === 'gaming' ? 'Игровая коллекция' : product.collection === 'quiet-evening' ? 'Тихий вечер' : undefined);
}

const tabletopLabels: Partial<Record<Kind, string>> = {
  collectible: 'фигурки', books: 'книги', plant: 'небольшие растения', lamp: 'настольные лампы', vase: 'вазы',
};

export function compatibleDecor(product: Product) {
  const surfaces = supportSurfaces(product);
  if (!surfaces.length) return undefined;
  const labels = new Set<string>();
  for (const candidate of catalog) {
    const label = tabletopLabels[candidate.kind];
    if (!label || !canPlaceOnTop(candidate)) continue;
    const fits = surfaces.some(surface => decorHeight(candidate) <= surface.clearance && [0, 90].some(rotation => {
      const { w, h } = dimensions(candidate, rotation);
      return w <= surface.w && h <= surface.h;
    }));
    if (fits) labels.add(label);
  }
  return labels.size ? [...labels].join(', ') : undefined;
}
